"""vfx.export: MP4, cover PNG, recipe ZIP and alpha-layer ZIP of a succeeded ``vfx.render`` job.

``mp4`` / ``cover_png`` return the render's own assets (no re-encode). The deliverable MP4 is the render's
``render_video_asset_id`` (with audio a render holds two ``render_video`` assets: the silent composite and the
muxed one, so the role is never used to pick it). ``recipe_zip`` packs what reproduces the ad (pinned config,
track/mask/plate metadata, preset, QA, workflow graphs, model manifest, input hashes). ``layers_zip`` re-renders the
effect layers deterministically from the render's own plan (``FrameComposer``) and streams them frame by frame:
``effect/%04d.png`` straight-alpha sRGB RGBA, ``foreground/%04d.png`` the source with the subject mask as alpha.
"""

