MODEL_MANIFEST = REPO_ROOT / "models" / "pocket-vfx.manifest.json"
WORKFLOW_APP_DIR = "pocket-vfx"
LAYER_ORDER = ["plate", "effect"]  # bottom -> top, over the (untouched) source; the subject is restored after them
LAYERS_NOTE = ("effect = plate + procedural effect after subject occlusion, straight alpha, sRGB. foreground = the "
               "source RGB with the SAM subject mask as alpha. The MP4 has no alpha channel.")


def _render_video_id(render: Job) -> str:
    res = render.result_json or {}
    if res.get("render_video_asset_id"):
        return str(res["render_video_asset_id"])
    return str(render.output_asset_ids[1])  # [layers, video, cover, roi_qa]


def _cover_id(render: Job) -> str:
    res = render.result_json or {}
    return str(res.get("cover_asset_id") or render.output_asset_ids[2])


def _input_doc(a) -> dict:
    return {"sha256": a.sha256, "mime": a.mime, "width": a.width, "height": a.height,
            "original_sha256": (a.meta_json or {}).get("original_sha256")}


def _job_doc(run: JobRun, j: Job) -> dict:
    stages = run.db.scalars(select(JobStage).where(JobStage.job_id == j.id)).all()
    return {"id": str(j.id), "kind": j.kind, "revision": j.input_revision, "profile": j.model_profile,
            "options": j.options_json,
            "stages": [{"name": s.stage_name, "state": s.state, "workflow_hash": s.workflow_hash,
                        "model_manifest_hash": s.model_manifest_hash, "build_id": s.build_id} for s in stages]}


def _is_mock(render: Job, masks: dict | None) -> bool:
    profile = PROFILES.get(render.model_profile)
    return bool((render.result_json or {}).get("mock")) or bool((masks or {}).get("mock")) or bool(
        profile is not None and profile.is_mock)


def _readme(render: Job, cfg: dict, plan: dict, track_key: str | None, mock: bool) -> str:
    res = render.result_json
    plate = plan["plate"]
    generated = res["render_profile"] == "generated"
    profile = PROFILES.get(render.model_profile)
    mock_line = ("**Mock profile** - tracking masks and/or the generated plate were deterministic CPU stand-ins "
                 "(Mock), not SAM 2.1 / LTX output.\n\n" if mock else "")
    mode = ("**Generated plate (생성 plate)**: the effect plate was generated by LTX for this effect and matted."
            if generated else
            "**Quick**: procedural effect + a bundled MIT-licensed plate. Nothing in this render is AI generated.")
    lines = [
        "# Pocket VFX recipe\n", mock_line + mode + "\n",
        "## This result\n",
        f"- Render job: `{render.id}`, project revision {render.input_revision}",
        (f"- Track job: `{plan['track_job_id']}`, track key `{track_key}`" if plan["track_job_id"] else
         "- Track job: none (fixed anchor, no subject masks)"),
        f"- Execution profile: {profile.label if profile else render.model_profile} (`{render.model_profile}`)",
        (f"- Effect: preset `{cfg['effect']['preset_id']}`, palette `{cfg['effect']['palette']}`, layer order "
         f"`{cfg['effect']['layer_order']}`, plate seed {cfg['plate']['seed']}"),
        (f"- Plate: {plate['source']} " + (f"`{plate['bundled_id']}`" if plate["bundled_id"] else
                                          f"asset `{plate['asset_id']}`") + f", {plate['frames']} frames")
        if plate else "- Plate: none (procedural effect only)",
        (f"- Output: {plan['canvas'][0]}x{plan['canvas'][1]}, {plan['frame_count']} frames @ 24 fps, "
         f"audio: {'yes' if res.get('has_audio') else 'no'}"),
        f"- Outside-ROI integrity: {res['roi_qa']['status']} (max channel error {res['roi_qa']['max_err']}/255)\n",
        "## Masks\n",
        ("SAM masks are segmentation, not alpha matting: edges are binary-derived and soft only through the "
         "resize, so hair and motion blur are not matted.\n"),
        "## Reproduce\n",
        "1. Install this repository and the models listed in `models/pocket-vfx.manifest.json`.",
        "2. Deploy the workflows from `workflows/pocket-vfx/` (copied under `workflows/` here).",
        ("3. Upload the clip whose hash is in `inputs.json`, apply `config.json`, run analyze, track "
         "(`track.json` / `masks.json` describe the result) and render. `plate.json` holds the plate source and "
         "its matte settings; `preset.json` the effect preset.\n"),
        ("The procedural effect and the Quick plate reproduce deterministically. Generated plates and SAM masks "
         "reproduce the same pipeline (graph, models, settings, seed); pixel-identical output is not guaranteed "
         "across GPUs or library versions.\n"),
    ]
    return "\n".join(lines)


def _recipe(run: JobRun, render: Job) -> str:
    rev = run.db.get(ProjectRevision, (run.project.id, render.input_revision))
    cfg = rev.config_json
    res = render.result_json or {}
    plan = json_asset(run, res["layers_asset_id"])
    preset = load_presets()[cfg["effect"]["preset_id"]]
    track_job = (source_job(run, plan["track_job_id"], ("vfx.track",), "track_required", "Track job not found.")
                 if plan["track_job_id"] else None)
    track_key = (track_job.result_json or {}).get("track_key") if track_job else None
    masks = plan["subject_masks"]
    mock = _is_mock(render, masks)

    inputs = {"clip": _input_doc(run.asset(cfg["video_asset_id"])), "work_clip": _input_doc(run.asset(cfg["work_asset_id"]))}
    if plan["plate"] and plan["plate"]["asset_id"]:
        inputs["plate"] = _input_doc(run.asset(plan["plate"]["asset_id"]))
    related = [render] + ([track_job] if track_job else [])
    track_doc = masks_doc = None
    if track_job is not None:
        track_asset = run.asset(track_job.result_json["track_asset_id"])
        inputs["track"] = _input_doc(track_asset)
        track_doc = json_asset(run, track_asset.id) if cfg["anchor"]["follow"] else None
    if masks is not None:
        zip_asset = run.asset(masks["masks_zip_asset_id"])
        inputs["masks_zip"] = _input_doc(zip_asset)
        with zipfile.ZipFile(run.fetch(zip_asset, "masks.zip")) as z:
            frames = json.loads(z.read("manifest.json"))
        masks_doc = {"masks_key": masks["masks_key"], "size": masks["size"], "diagnostics": masks["diagnostics"],
                     "format": "masks.zip: mask_%04d.png 1-bit proxy-size segmentation (255 = subject), "
                               "not alpha matting", "manifest": frames}
    qa = {"roi_qa": res["roi_qa"], "occlusion_qa": res["occlusion_qa"], "occlusion": res["occlusion"],
          "tracking_warnings": res["tracking_warnings"], "mask_warnings": res["mask_warnings"],
          "has_audio": res["has_audio"], "audio": res["audio"]}

    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED) as z:
        z.writestr("README.md", _readme(render, cfg, plan, track_key, mock))
        z.writestr("config.json", json.dumps({"revision": render.input_revision, "track_key": track_key,
                                               "render_options": render.options_json, "config": cfg}, indent=2))
        z.writestr("preset.json", json.dumps(preset, indent=2, ensure_ascii=False))
        if track_doc is not None:
            z.writestr("track.json", json.dumps({"track_key": track_key, **track_doc}, indent=2))
        if masks_doc is not None:
            z.writestr("masks.json", json.dumps(masks_doc, indent=2))
        z.writestr("plate.json", json.dumps({"plate": plan["plate"], "config": cfg["plate"]}, indent=2))
        z.writestr("layers.json", json.dumps(plan, indent=2))
        z.writestr("qa.json", json.dumps(qa, indent=2))
        z.writestr("jobs.json", json.dumps([_job_doc(run, j) for j in related], indent=2))
        z.writestr("inputs.json", json.dumps(inputs, indent=2))
        z.write(MODEL_MANIFEST, "models/pocket-vfx.manifest.json")
        wf_dir = Path(run.ctx.settings.workflows_dir) / WORKFLOW_APP_DIR
        if wf_dir.is_dir():
            for f in sorted(wf_dir.glob("*.json")):
                z.write(f, f"workflows/{f.name}")
            if (wf_dir / "README.md").exists():
                z.write(wf_dir / "README.md", "workflows/README.md")
    path = run.work_dir / "recipe.zip"
    path.write_bytes(buf.getvalue())
    return run.store_asset("recipe", path, "application/zip", source_asset_id=_render_video_id(render),
                           meta={"revision": render.input_revision, "render_job_id": str(render.id),
                                 "track_key": track_key, **({"mock": True} if mock else {})})


# ---- layers ZIP ------------------------------------------------------------------------------------------


def effect_rgba(layers: list[EffectLayer], subject: np.ndarray | None, w: int, h: int) -> np.ndarray:
    """Straight-alpha sRGB RGBA (uint8 HxWx4) of the behind layers (plate, then effect) over transparency, after the
    subject occlusion the composite applies (``alpha * (1 - subject)``). Blending is premultiplied in linear."""
    out = np.zeros((h, w, 4), np.uint8)
    if not layers:
        return out
    boxes = [layer.bbox for layer in layers]
    x0, y0, x1, y1 = (0, 0, w, h) if any(b is None for b in boxes) else (
        max(min(b[0] for b in boxes), 0), max(min(b[1] for b in boxes), 0),
        min(max(b[2] for b in boxes), w), min(max(b[3] for b in boxes), h))
    if x0 >= x1 or y0 >= y1:
        return out
    sl = (slice(y0, y1), slice(x0, x1))
    rgb = np.zeros((y1 - y0, x1 - x0, 3), np.float32)  # premultiplied linear
    keep = np.ones((y1 - y0, x1 - x0), np.float32)
    for layer in layers:
        rgb = over_premult(rgb, layer.rgb_premult[sl], layer.alpha[sl])
        keep *= 1.0 - layer.alpha[sl]
    alpha = 1.0 - keep
    if subject is not None:
        m = np.clip(subject[sl], 0.0, 1.0)
        rgb, alpha = rgb * (1.0 - m)[..., None], alpha * (1.0 - m)
    straight = np.where(alpha[..., None] > 0, rgb / np.maximum(alpha, 1e-12)[..., None], 0.0)
    out[sl][..., :3] = linear_to_srgb(straight)
    out[sl][..., 3] = np.rint(np.clip(alpha, 0.0, 1.0) * 255.0).astype(np.uint8)
    return out


def _png(rgba: np.ndarray) -> bytes:
    buf = io.BytesIO()
    Image.fromarray(rgba, "RGBA").save(buf, "PNG", compress_level=3)
    return buf.getvalue()


def _layers_readme(has_fg: bool, mock: bool) -> str:
    return (
        "# Pocket VFX layers\n\n" + ("**Mock profile**: stand-in masks/plates, not SAM/LTX output.\n\n" if mock else "")
        + "- `effect/%04d.png`: the effect layers combined (plate + procedural effect, after the subject occlusion "
          "of the render), straight (un-premultiplied) alpha, sRGB, RGBA, one PNG per frame.\n"
        + ("- `foreground/%04d.png`: the source frame as RGB with the subject mask (upscaled SAM mask) as alpha.\n"
           if has_fg else "- No `foreground/` folder: this render had no subject masks.\n")
        + "- `manifest.json`: frame count, fps, size, layer order, color handling.\n\n"
          "**The MP4 has no alpha channel**; use these PNGs to composite the effect yourself.\n\n"
          "**SAM masks are segmentation, not alpha matting**: the foreground alpha is a silhouette that is only "
          "softened by resizing. Hair, motion blur and semi-transparent edges are not matted.\n")


def _layers_zip(run: JobRun, render: Job) -> str:
    cfg, cfg_json = run.config(), run.config().model_dump(mode="json")
    res = render.result_json or {}
    plan = json_asset(run, res["layers_asset_id"])
    w, h, n = canvas(cfg)
    if [w, h] != plan["canvas"] or n != plan["frame_count"]:
        raise StageFailed("render_mismatch", "The render does not match its project revision.")
    window = effect_window(cfg_json["effect"], cfg.trim.duration_ms)
    work = fresh_work_clip(run, cfg, cfg_json)
    composer = FrameComposer(run, cfg, cfg_json, plan, window, w, h, n)
    has_fg = composer.masks is not None
    order = cfg.effect.layer_order
    path = run.work_dir / "layers.zip"
    count = 0
    with zipfile.ZipFile(path, "w", zipfile.ZIP_STORED) as z:
        for i, frame in enumerate(with_heartbeat(run, decode_frames(run.fetch(work, "work.mp4")), 5)):
            if i >= n:
                break
            inp, subject = composer.inputs(i, frame)
            rgba = effect_rgba([x for x in (inp.plate, inp.effect) if x is not None], subject, w, h)
            _, roi = composite_frame(inp, order)  # the render's own ROI of this frame
            if ((rgba[..., 3] > 0) & ~roi).any():
                raise StageFailed("layers_outside_roi", f"Effect alpha lies outside the render's ROI at frame {i}.")
            z.writestr(f"effect/{i:04d}.png", _png(rgba))
            if has_fg:
                fg = np.dstack([frame, np.rint(np.clip(composer.subject_at(i), 0.0, 1.0) * 255.0).astype(np.uint8)])
                z.writestr(f"foreground/{i:04d}.png", _png(fg))
            count += 1
        if count != n:
            raise StageFailed("frame_count_mismatch", f"Exported {count} frames, expected {n}.")
        manifest = {"schema_version": 1, "frame_count": n, "fps": 24, "size": [w, h], "layer_order": LAYER_ORDER,
                    "layer_order_mode": order, "premultiplied": False, "color": "sRGB",
                    "folders": ["effect", *(["foreground"] if has_fg else [])],
                    "foreground": ("subject mask as alpha over the source RGB" if has_fg else
                                   "omitted: the render had no subject masks"),
                    "alpha_floor": ALPHA_FLOOR, "render_job_id": str(render.id), "revision": render.input_revision,
                    "note": LAYERS_NOTE}
        z.writestr("manifest.json", json.dumps(manifest, indent=2))
        z.writestr("README.md", _layers_readme(has_fg, _is_mock(render, plan["subject_masks"])))
    return run.store_asset("layers_export", path, "application/zip", source_asset_id=_render_video_id(render),
                           meta={"revision": render.input_revision, "render_job_id": str(render.id),
                                 "frame_count": n, "foreground": has_fg})


def vfx_export(run: JobRun) -> tuple[list[str], dict]:
    opts = run.job.options_json
    render = source_job(run, opts.get("render_job_id"), tuple(VFX_APP.export_formats), "render_not_found",
                        "Render job not found.")
    fmt = opts["format"]
    if fmt not in VFX_APP.export_formats[render.kind]:
        raise StageFailed("invalid_format", f"unknown export format {fmt}")
    if fmt == "mp4":
        outputs = [_render_video_id(render)]
    elif fmt == "cover_png":
        outputs = [_cover_id(render)]
    elif fmt == "recipe_zip":
        outputs = run.ensure_stage("recipe", lambda st: [_recipe(run, render)])
    else:  # layers_zip
        outputs = run.ensure_stage("layers_zip", lambda st: [_layers_zip(run, render)])
    return outputs, {"format": fmt, "render_job_id": str(render.id), "revision": render.input_revision}
